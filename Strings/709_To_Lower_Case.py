# Problem: To Lower Case
# LeetCode: 709
#
# Approach: Built-in String Method
# --------------------------------
# Convert all uppercase letters in the string
# to lowercase using Python's lower() method.
#
# Time Complexity: O(n)
# Space Complexity: O(n)

class Solution(object):
    def toLowerCase(self, s):
        """
        :type s: str
        :rtype: str
        """

        return s.lower()
